def _run(executor) -> dict:
    """Record one run on the canonical match without wall-clock durations."""
    return asyncio.run(record_agent_run(executor, clock=lambda: None))


def _specialists(trace: dict) -> list[dict]:
    """The specialist turns, in order."""
    return [step for step in trace["steps"] if step["type"] == "specialist"]


def test_rehearsal_runs_every_role_and_loops_on_a_failed_verification() -> None:
    """A misstated number is caught by code, sent back, recomputed and then verified."""
    trace = rehearsal_trace()
    assert trace["status"] == "completed"
    assert [s["role"] for s in _specialists(trace)] == [
        "tactical_analyst",
        "narrative_composer",
        "editorial_reviewer",
        "narrative_composer",
        "editorial_reviewer",
        "audience_adapter",
    ]
    rounds = [s for s in trace["steps"] if s["type"] == "verification"]
    first, second = rounds
    assert first["passed"] is False and second["passed"] is True
    failed = [r for r in first["results"] if r["status"] == "needs_revision"]
    assert [r["claim_id"] for r in failed] == ["NC-02"]
    assert failed[0]["observed"] == pytest.approx(0.5796, abs=1e-4)
    assert {r["status"] for r in second["results"]} == {"verified", "supported_inference"}
    # The editorial reviewer dropped the claim no registered query can check.
    review = _specialists(trace)[2]
    assert "NC-04" not in [c["claim_id"] for c in review["claims"]]
    assert "season history" in review["content"]
    assert len(trace["variants"]) == 9
    assert all(
        v["language_review"] == "NOT_RUN" and not v["publishable"] for v in trace["variants"]
    )
    assert trace["published"] is False and trace["provider"]["kind"] == "rehearsal"


def test_each_role_used_only_its_scoped_tools() -> None:
    """Tool calls are recorded per role and stay inside the host's permission matrix."""
    allowed = {
        "tactical_analyst": {"metric", "event_by_id", "events_in_window"},
        "narrative_composer": {"metric", "event_by_id", "events_in_window", "verification_result"},
        "editorial_reviewer": {"metric", "event_by_id", "events_in_window", "verification_result"},
        "audience_adapter": {"verification_result"},
    }
    trace = rehearsal_trace()
    for step in _specialists(trace):
        assert {call["tool"] for call in step["tool_calls"]} <= allowed[step["role"]]
    assert _specialists(trace)[0]["tool_calls"], "the analyst read the match through its tools"
    assert trace["totals"]["tool_calls"] == sum(len(s["tool_calls"]) for s in _specialists(trace))


